export type TranslationKey = keyof typeof dict.pt;

type I18nContextValue = {
  locale: Locale;
  setLocale: (l: Locale) => void;
  t: (key: TranslationKey) => string;
  dateLocale: DateFnsLocale;
  formatDate: (value?: string) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() => {
    const saved = localStorage.getItem(STORAGE_KEY);
    return saved === 'en' ? 'en' : 'pt';
  });

  const setLocale = useCallback((l: Locale) => {
    setLocaleState(l);
    localStorage.setItem(STORAGE_KEY, l);
  }, []);

  const t = useCallback((key: TranslationKey) => dict[locale][key] ?? key, [locale]);

  const dateLocale = locale === 'en' ? enUS : ptBR;

  const formatDate = useCallback(
    (value?: string) => {
      if (!value) return '—';
      return new Date(value).toLocaleString(locale === 'en' ? 'en-US' : 'pt-BR');
    },
    [locale],
  );

  useEffect(() => {
    document.documentElement.lang = locale === 'en' ? 'en' : 'pt-BR';
  }, [locale]);

  return (
    <I18nContext.Provider value={{ locale, setLocale, t, dateLocale, formatDate }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used within I18nProvider');
  return ctx;
}

export function LanguageToggle({ onDark = false }: { onDark?: boolean }) {
  const { locale, setLocale, t } = useI18n();
  const inactive = onDark
    ? 'text-white/80 hover:bg-white/10'
    : 'text-on-surface-variant hover:bg-surface-variant';
  const active = onDark
    ? 'bg-white text-primary-container'
    : 'bg-primary-container text-on-primary-container';
  return (
    <div className={clsx('flex rounded-lg border overflow-hidden text-sm font-mono', onDark ? 'border-white/30' : 'border-outline-variant')}>
      <button
        type="button"
        onClick={() => setLocale('pt')}
        className={`px-3 py-1.5 ${locale === 'pt' ? active : inactive}`}
      >
        {t('lang.pt')}
      </button>
      <button
        type="button"
        onClick={() => setLocale('en')}
        className={`px-3 py-1.5 ${locale === 'en' ? active : inactive}`}
      >
        {t('lang.en')}
      </button>
    </div>
  );
}
